PAIRS = [("이라", "라"), ("이랑", "랑"), ("으로", "로"), ("은", "는"), ("이", "가"), ("을", "를"), ("과", "와"), ("아", "야")]


def jong(word: str) -> int:
    c = word[-1]
    if "가" <= c <= "힣":
        return (ord(c) - 0xAC00) % 28
    if c.isdigit():
        return 0 if c in "2459" else 1
    return 0


def particle(word: str, cons: str, vow: str) -> str:
    j = jong(word)
    if cons == "으로":
        return "로" if j in (0, 8) else "으로"
    return cons if j else vow


ALL_P = sorted({p for pair in PAIRS for p in pair}, key=len, reverse=True)
P_RE = "|".join(ALL_P)


def rename(text: str, old: str, new: str) -> str:
    """old 뒤에 바로 붙은 조사를 new의 받침에 맞게 바꾸며 교체 (다음 글자가 한글이면 조사가 아닐 수 있어 1글자 조사는 경계 확인)"""
    def fix(m: re.Match) -> str:
        p = m.group(1) or ""
        nxt = m.group(2) or ""
        if p:
            for cons, vow in PAIRS:
                if p in (cons, vow):
                    # '이다'/'이에요' 같은 서술격은 건드리지 않음, 한 글자 조사 뒤에 한글이 이어지면 조사가 아닐 수 있음
                    if len(p) == 1 and nxt and "가" <= nxt <= "힣" and p not in ("은", "는", "을", "를", "과", "와"):
                        return new + p + nxt
                    return new + particle(new, cons, vow) + nxt
        return new + p + nxt
    return re.sub(re.escape(old) + "(" + P_RE + ")?(.)?", fix, text, flags=re.S)



def check_patterns():
    folder = os.path.join(ROOT, "scripts")
    bad = []
    for f, pairs in S.items():
        src = open(os.path.join(folder, f), encoding="utf-8", newline="").read()
        bad += ["%s: %s" % (f, a) for a, _ in pairs if a not in src]
    if bad:
        raise SystemExit("못 찾음:\n" + "\n".join(bad))


def scripts_pass():
    folder = os.path.join(ROOT, "scripts")
    for f in sorted(os.listdir(folder)):
        if not f.endswith(".gd") or f == "savecode.gd":
            continue
        p = os.path.join(folder, f)
        s = open(p, encoding="utf-8", newline="").read()
        for a, b in S.get(f, []):
            if a not in s:
                raise SystemExit("못 찾음 %s: %s" % (f, a))
            s = s.replace(a, b)
        s = text_pass(s, [])
        open(p, "w", encoding="utf-8", newline="").write(s)
    p = os.path.join(ROOT, "tests", "regression.gd")
    s = open(p, encoding="utf-8", newline="").read()
    for a, b in TESTS:
        s = s.replace(a, b)
    open(p, "w", encoding="utf-8", newline="").write(text_pass(s, []))



def walk(x, f):
    if isinstance(x, str):
        return f(x)
    if isinstance(x, list):
        return [walk(v, f) for v in x]
    if isinstance(x, dict):
        return {k: walk(v, f) for k, v in x.items()}
    return x


def text_pass(s: str, lines) -> str:
    for a, b in lines:
        s = s.replace(a, b)
    for a, b in NAMES:
        if a in s:
            s = rename(s, a, b)
    return s


def data_pass():
    d = json.load(open(DATA, encoding="utf-8"))
    d["types"]["fire"]["n"] = "불"
    d["status"]["par"]["n"] = "저림"
    d["status"]["slp"]["n"] = "졸음"
    d["pockets"] = [[p[0], "조사 도구" if p[0] == "key" else p[1]] for p in d["pockets"]]
    for i, n in enumerate(NATURES):
        d["natures"][i][0] = n
    for k, v in TCLASS.items():
        if k in d["tclass"]:
            d["tclass"][k]["n"] = v
    for sid, lv in EVOS.items():
        sp = d["species"][str(sid)]
        sp["ev"][0] = lv
    for sid, t in TYPES.items():
        d["species"][str(sid)]["t"] = t
    for sid, s in DESC.items():
        d["species"][str(sid)]["d"] = s
    d = walk(d, lambda s: text_pass(s, DATA_LINES))
    for k, (n, price, desc) in ITEMS.items():
        it = d["items"][k]
        it["n"] = n
        if price is not None:
            it["price"] = price
        if desc:
            it["d"] = desc
    for k, n in MOVES.items():
        d["moves"][k]["n"] = n
    json.dump(d, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))


